<h1>Find a time that works for everyone</h1>
<p class="lead">
	Meetful replaces the “does Tuesday work?” thread. Propose a few times, share one link, and see at a
	glance which time suits the most people.
</p>

<h2>How it works</h2>
<ol>
	<li><strong>Create a poll.</strong> Add a title and the times you could meet, including all-day options.</li>
	<li><strong>Share it.</strong> Send the link or a short join code. Guests can answer without making an account.</li>
	<li><strong>Pick the time.</strong> Everyone marks each option available, maybe or unavailable, and you see the best fit as answers come in.</li>
</ol>

<h2>Why Meetful</h2>
<ul>
	<li><strong>Checks your calendar for you.</strong> Connect Google Calendar, or use your phone’s calendar on iPhone and Android, and Meetful flags the times you’re already busy. Your phone’s events stay on your phone, and from Google Calendar Meetful sees only when you’re busy.</li>
	<li><strong>Works where you are.</strong> Use it on iPhone, Android or the web. Your polls stay in sync.</li>
	<li><strong>No ads.</strong> We don’t sell your data or show ads. Read the <a href="/privacy">privacy policy</a>.</li>
</ul>


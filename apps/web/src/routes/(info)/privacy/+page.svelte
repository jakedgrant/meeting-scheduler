<h1>Privacy Policy</h1>
<p class="updated">Last updated November 18, 2026</p>

<p>
	Meetful helps groups find a meeting time. This policy explains what we collect when you use the
	Meetful website and the iPhone and Android apps, why we collect it, and the choices you have. We
	don’t sell your personal information or show ads.
</p>

<h2>What we collect</h2>
<ul>
	<li>
		<strong>Your account.</strong> When you sign in with Google, Apple or an email link, we receive your
		email address and, if the provider shares them, your name and profile picture. We also keep your
		time zone so times display correctly.
	</li>
	<li>
		<strong>Polls and responses.</strong> The polls you create (title, description, location and
		proposed times) and the answers, notes and comments you add to polls.
	</li>
	<li>
		<strong>Guests.</strong> If you answer a poll without an account, we keep the name you enter and,
		if you provide one, your email address.
	</li>
	<li>
		<strong>Purchases.</strong> If you subscribe or buy a pass, the App Store, Google Play or our web
		payment provider handles payment. We receive the product, its status and transaction identifiers,
		never your card details.
	</li>
	<li>
		<strong>Usage and crash data on Android.</strong> The Android app uses Google’s Firebase Analytics
		and Crashlytics to count how the app is used and to report crashes. They collect device details, an
		app installation identifier, the Android advertising ID, approximate location from your IP
		address, the screens you open and how long you use the app, and crash logs. The website and the iPhone app use no third-party
		analytics.
	</li>
</ul>

<h2>Calendar access</h2>
<p>
	Calendar access is optional. Meetful uses it to mark the proposed times when you’re already busy
	and, when you ask, to add a meeting to your calendar.
</p>
<ul>
	<li>
		<strong>Google Calendar.</strong> If you connect it, we ask Google for free/busy access and the
		email address of the Google account you connect. We can see when you’re busy, but not event titles,
		attendees or other details. Your Google tokens are stored encrypted. Disconnecting removes them from
		your account and asks Google to revoke access; we keep an encrypted copy only until Google confirms
		the revocation.
	</li>
	<li>
		<strong>Your phone’s calendar.</strong> On iPhone and Android, the app checks your calendar on the
		device. On iPhone it can also show you which of your events conflict with a proposed time. Your
		events aren’t sent to us.
	</li>
</ul>

<h2>How we use it</h2>
<p>
	We use this information to run Meetful: to sign you in, show your polls, let other participants see
	responses, check calendar conflicts, apply your plan’s features, fix crashes and keep the service
	secure. We don’t use it for advertising.
</p>

<h2>Who can see it</h2>
<ul>
	<li>
		<strong>People in your polls.</strong> Anyone with a poll’s link or join code can see the poll.
		Participants can see each other’s names, profile pictures, answers, notes and comments.
	</li>
	<li>
		<strong>Service providers.</strong> We rely on Supabase to host our database and sign-in,
		RevenueCat to manage subscriptions, Google and Apple for sign-in, Google for calendar access, Google
		Firebase for Android usage and crash reports, and Vercel to host the website. We share
		with each only what it needs to provide its service.
	</li>
	<li>
		<strong>When required.</strong> We may disclose information if the law requires it or to protect
		people’s safety and the security of the service.
	</li>
</ul>

<h2>Cookies and local storage</h2>
<p>
	We use your browser’s storage to keep you signed in, to let you return to polls you answered as a
	guest, to hold unsaved polls and answers, and to remember access during the private alpha. We don’t
	use advertising or tracking cookies.
</p>

<h2>Keeping and deleting your data</h2>
<p>
	We keep your information while your account exists. To delete your account, email
	<a href="mailto:privacy@meetful.app">privacy@meetful.app</a> from the address you sign in with.
	Deleting your account removes your profile, the polls you created and your calendar connection. In
	other people’s polls, your answers stay so their results still add up, but your name is replaced
	with “Deleted user” and your notes and comments are removed.
</p>
<p>
	If you answered a poll as a guest, your name, email, answers, notes and comments stay until the
	poll is deleted. To have them removed sooner, email
	<a href="mailto:privacy@meetful.app">privacy@meetful.app</a> with the poll link and the name you
	used.
</p>
<p>
	You can also email us to get a copy of your information or to correct it. Depending on where you
	live, you may have further rights under laws such as the GDPR or CCPA, and we’ll honor them.
</p>

<h2>Children</h2>
<p>Meetful isn’t meant for children under 13, and we don’t knowingly collect their information.</p>

<h2>Changes to this policy</h2>
<p>
	If we change this policy, we’ll update the date at the top of this page. For significant changes,
	we’ll let you know in the app or by email.
</p>

<h2>Contact</h2>
<p>Questions about privacy? Email <a href="mailto:privacy@meetful.app">privacy@meetful.app</a>.</p>

